import os
import sqlite3

import psycopg
from dotenv import load_dotenv

load_dotenv()

SQLITE_PATH = "data/context.db"
NEON_DATABASE_URL = os.getenv("NEON_DATABASE_URL")

TABLES = [
    "users",
    "profiles",
    "preferences",
    "conversation_messages",
    "job_tracking",
    "job_events",
]


def migrate():
    if not NEON_DATABASE_URL:
        raise RuntimeError("NEON_DATABASE_URL is not configured.")

    sqlite_conn = sqlite3.connect(SQLITE_PATH)
    sqlite_conn.row_factory = sqlite3.Row

    try:
        with psycopg.connect(NEON_DATABASE_URL) as pg_conn:
            with pg_conn.cursor() as cursor:

                # Refuse to overwrite an existing database.
                for table in TABLES:
                    cursor.execute(
                        """
                        SELECT EXISTS (
                            SELECT 1
                            FROM information_schema.tables
                            WHERE table_schema = 'public'
                              AND table_name = %s
                        )
                        """,
                        (table,),
                    )

                    if cursor.fetchone()[0]:
                        cursor.execute(
                            f'SELECT COUNT(*) FROM "{table}"'
                        )

                        if cursor.fetchone()[0] > 0:
                            raise RuntimeError(
                                f"Neon table '{table}' already "
                                "contains data. Migration cancelled."
                            )

                # Create tables in dependency order.
                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY
                            PRIMARY KEY,
                        user_id TEXT UNIQUE NOT NULL
                    )
                """)

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS profiles (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY
                            PRIMARY KEY,
                        user_id TEXT UNIQUE NOT NULL
                            REFERENCES users(user_id),
                        target_role TEXT,
                        experience_level TEXT,
                        skills TEXT
                    )
                """)

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS preferences (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY
                            PRIMARY KEY,
                        user_id TEXT UNIQUE NOT NULL
                            REFERENCES users(user_id),
                        remote_only INTEGER DEFAULT 0,
                        preferred_locations TEXT,
                        preferred_skills TEXT
                    )
                """)

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS conversation_messages (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY
                            PRIMARY KEY,
                        user_id TEXT NOT NULL
                            REFERENCES users(user_id),
                        role TEXT NOT NULL,
                        content TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """)

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS job_tracking (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY
                            PRIMARY KEY,
                        user_id TEXT NOT NULL
                            REFERENCES users(user_id),
                        job_id TEXT NOT NULL,
                        title TEXT,
                        job_url TEXT,
                        status TEXT DEFAULT 'saved',
                        saved_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        applied_at TIMESTAMP,
                        UNIQUE(user_id, job_id)
                    )
                """)

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS job_events (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY
                            PRIMARY KEY,
                        user_id TEXT NOT NULL
                            REFERENCES users(user_id),
                        job_id TEXT NOT NULL,
                        event_type TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """)

                # Copy data while preserving existing IDs.
                for table in TABLES:
                    rows = sqlite_conn.execute(
                        f'SELECT * FROM "{table}"'
                    ).fetchall()

                    if not rows:
                        print(f"{table}: 0 records")
                        continue

                    columns = rows[0].keys()
                    column_sql = ", ".join(
                        f'"{column}"' for column in columns
                    )
                    placeholders = ", ".join(
                        ["%s"] * len(columns)
                    )

                    insert_sql = (
                        f'INSERT INTO "{table}" ({column_sql}) '
                        f"VALUES ({placeholders})"
                    )

                    values = [
                        tuple(row[column] for column in columns)
                        for row in rows
                    ]

                    cursor.executemany(insert_sql, values)
                    print(f"{table}: migrated {len(rows)} records")

                # Keep identity counters aligned with copied IDs.
                for table in TABLES:
                    cursor.execute(
                        """
                        SELECT column_name
                        FROM information_schema.columns
                        WHERE table_schema = 'public'
                          AND table_name = %s
                          AND is_identity = 'YES'
                        """,
                        (table,),
                    )

                    identity_column = cursor.fetchone()

                    if identity_column:
                        column = identity_column[0]
                        cursor.execute(
                            f'SELECT MAX("{column}") FROM "{table}"'
                        )
                        max_id = cursor.fetchone()[0]

                        if max_id is not None:
                            cursor.execute(
                                """
                                SELECT setval(
                                    pg_get_serial_sequence(%s, %s),
                                    %s,
                                    true
                                )
                                """,
                                (f"public.{table}", column, max_id),
                            )

            # psycopg commits the transaction when the context exits
            # successfully, or rolls it back if an exception occurs.

        print("\nMigration completed successfully.")

    finally:
        sqlite_conn.close()


if __name__ == "__main__":
    migrate()